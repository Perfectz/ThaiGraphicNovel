/**
 * Data for the standalone JRPG-style battle conversation demo.
 *
 * The fight is framed as a polite first meeting with the Rift Guardian. Patrick
 * speaks Thai to move the conversation forward; Su's support moves either coach
 * the phrase or politely explains Patrick's beginner status.
 */

export type BattleElement = 'slash' | 'fire' | 'ice' | 'lightning' | 'holy' | 'wind' | 'shadow';

export type ConversationMoveKind = 'standard' | 'super' | 'heal' | 'defend' | 'counter';

export type DemoTechnique = {
  id: string;
  name: string;
  thai: string;
  romanization: string;
  translation: string;
  element: BattleElement;
  power: number;
  mpCost: number;
  description: string;
  battleCry: string;
  kind: ConversationMoveKind;
  turnIndex: number;
  prompt: string;
  suLine?: string;
  isHeal?: boolean;
  effect?: 'guard' | 'charge';
};

export type ConversationTurn = {
  id: string;
  turnNo: number;
  topic: string;
  enemyLine: string;
  simple: DemoTechnique;
  super: DemoTechnique;
  heal: DemoTechnique;
  defend: DemoTechnique;
  counter: DemoTechnique;
};

function move(
  turnIndex: number,
  kind: ConversationMoveKind,
  id: string,
  name: string,
  thai: string,
  romanization: string,
  translation: string,
  power: number,
  mpCost: number,
  element: BattleElement,
  description: string,
  battleCry: string,
  prompt: string,
  suLine?: string,
): DemoTechnique {
  return {
    id,
    name,
    thai,
    romanization,
    translation,
    element,
    power,
    mpCost,
    description,
    battleCry,
    kind,
    turnIndex,
    prompt,
    suLine,
    isHeal: kind === 'heal',
    effect: kind === 'defend' ? 'guard' : kind === 'super' ? 'charge' : undefined,
  };
}

